class TouchLlavaLlamaForCausalLM(LlamaForCausalLM, LlavaMetaForCausalLM):
    config_class = LlavaConfig

    def __init__(self, config):
        super(LlamaForCausalLM, self).__init__(config)
        self.model = LlavaLlamaModel(config)
        self.pretraining_tp = config.pretraining_tp
        self.vocab_size = config.vocab_size
        self.lm_head = nn.Linear(config.hidden_size, config.vocab_size, bias=False)

        # Initialize weights and apply final processing
        self.post_init()

    def get_model(self):
        return self.model

    def extract_modality_embeddings(self, images, touchs):
        """
        Extract vision and tactile embeddings before LLM fusion.
        Used for routing decision.
        """
        model = self.get_model()

        # 取 vision tower
        z_v = model.get_vision_tower()(images)
        z_v = z_v.to(model.dtype)
        z_v = model.mm_projector(z_v)
        # 取 tactile tower
        z_t = model.get_touch_tower().touch_model(touchs)
        z_t = z_t[0][:,1:,:]
        z_t = z_t.to(model.dtype)
        z_t = model.mm_touch_projector(z_t)
        
        return z_v, z_t
    
